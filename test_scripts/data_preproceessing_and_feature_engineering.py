def preprocess(df):
  """
  Cleaning merged datasets
  """
  df = df.copy()
  n_starting = len(df)

  df = df.drop_duplicates()
  n_after = len(df)
  n_duplicates = n_starting - n_after
  print(f"Dropped {n_duplicates:,} duplicate rows.")

  dedup_cols = ["latitude", "longitude", "acq_date", "acq_time"]
  missing_dedup = [c for c in dedup_cols if c not in df.columns]
  if missing_dedup:
    raise KeyError(f"Dedup columns missing: {missing_dedup} -- skipping near-dup check.")

  else:
    df = df.drop_duplicates(subset=dedup_cols)
    n_dedup = n_starting - len(df)
    print(f"Dropped {n_dedup:,} near-duplicate rows.")

  # Confidence Filter
  if 'confidence' in df.columns:
    n_before = len(df)
    df = df[df['confidence'].isin(CONFIDENCE_TOKEEP)].copy()
    print(f"Dropped {n_before - len(df):,} rows with low confidence.")

  if 'type' in df.columns:
    n_before = len(df)
    df = df[df['type'].isin(TYPE_TOKEEP)].copy()
    print(f"Dropped {n_before - len(df):,} Keeping rows with Vegetation fire only, type = 0.")

  # ---- Sort chronologically per grid cell -------------------------------
    lat_col = "lat_round" if "lat_round" in df.columns else "latitude"
    lon_col = "lon_round" if "lon_round" in df.columns else "longitude"
    sort_cols = [lat_col, lon_col] + [c for c in ["acq_date", "acq_time"] if c in df.columns]
    df = df.sort_values(sort_cols).reset_index(drop=True)
    print("Sorted chronologically per grid cell (required for cumulative "
             "KBDI / Drought Factor computation).")

  # ---- Coordinate bounds check -------------------------------------------
    out_of_bounds = (~df[lat_col].between(LAT_MIN, LAT_MAX) |
                      ~df[lon_col].between(LON_MIN, LON_MAX))
    n_oob = int(out_of_bounds.sum())
    if n_oob:
        print(f"{n_oob:,} rows outside the Australia bbox -- dropping.")
        df = df[~out_of_bounds].reset_index(drop=True)
    else:
        print("Coordinate bounds check passed.")

    print(f"Preprocessing done -- final rows: {len(df):,} "
             f"(dropped {n_starting - len(df):,} , "
             f"{100 * (n_starting - len(df)) / n_starting:.2f}%")
    return df

