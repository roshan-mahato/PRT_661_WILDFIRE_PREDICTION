def compute_emc(rh, temp_c):
  """
  Equilibrium Moisture Content (Simard, 1968).
  Piecewise formula depending on relative humidity band.
  rh: relative humidity (%), temp_c: air temperature (deg C)
  """
  emc = np.empty_like(rh, dtype=float)

  low = rh < 10
  mid = (rh >= 10) & (rh < 50)
  high = rh >= 50

  emc[low] = 0.03229 + 0.281073 * rh[low] - 0.000578 * rh[low] * temp_c[low]
  emc[mid] = 2.22749 + 0.160107 * rh[mid] - 0.014784 * temp_c[mid]
  emc[high] = (21.0606 + 0.005565 * rh[high] ** 2 - 0.00035 * rh[high] * temp_c[high] - 0.483199 * rh[high])
  return emc

