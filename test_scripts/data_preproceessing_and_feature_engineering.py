def compute_kbdi_and_df(group):
    """
    Computes KBDI (Keetch & Byram, 1968) and Drought Factor (Griffiths, 1999)
    for a single grid cell's rows, in chronological order.

    Both are recursive: each day's value depends on the previous day's value
    plus that day's rainfall/temperature. Because our data only has rows on
    days a hotspot was actually detected (not a continuous daily series), we
    track the actual elapsed days between consecutive rows and use that as
    `dt` in the KBDI update -- an approximation for gappy data, not a
    substitute for a continuous daily record (see module docstring).
    """
    # Number of calendar days a grid cell needs before KBDI is considered past
    # its spin-up period. Rows before this are flagged, not dropped, so you can
    # decide at analysis time whether to exclude them.
    KBDI_SPINUP_DAYS = 30

    # Mean annual rainfall (mm) -- KNOWN LIMITATION: this is a single
    # Australia-wide constant, not a per-cell climatology value. Replace with a
    # real spatial lookup if/when that data becomes available.
    MEAN_ANNUAL_RAINFALL_MM = 700.0
    group = group.reset_index(drop=True)
    n = len(group)

    kbdi = np.zeros(n)
    drought_factor = np.zeros(n)
    days_since_rain = np.zeros(n)
    last_rain_amount = np.zeros(n)
    days_since_cell_start = np.zeros(n)

    # Pull everything into plain numpy/python arrays BEFORE the loop.
    # Per-row pandas .loc access (as in an earlier version of this script)
    # is extremely slow at millions of rows -- plain array indexing here
    # is roughly 100x faster for this kind of row-by-row recursive update.
    dates = group["acq_date"].to_numpy()
    temps = group["temperature_2m"].to_numpy(dtype=float)
    rains = group["precipitation"].fillna(0.0).clip(lower=0.0).to_numpy(dtype=float) \
        if "precipitation" in group.columns else np.zeros(n)

    # Days-elapsed between consecutive rows, in whole days (numpy datetime64
    # arithmetic, computed once, vectorised, outside the loop)
    if n > 1:
        gaps_days = np.empty(n)
        gaps_days[0] = 1.0
        gaps_days[1:] = np.maximum(
            (dates[1:] - dates[:-1]) / np.timedelta64(1, "D"), 1
        )
    else:
        gaps_days = np.array([1.0])

    q_prev = 0.0             # KBDI starts at 0 (recently wet) -- a simplifying
                              # assumption; a real implementation would seed
                              # this from antecedent conditions if known.
    n_dry_days = 0.0
    last_rain_amt = 0.0

    # FIX 1: rain-event tracking. The original version subtracted the 5mm
    # canopy-interception buffer on every rainy row -- across a multi-day
    # rain spell that means the same interception gets subtracted 2, 3, 4+
    # times, which isn't what KBDI's interception term represents (it's a
    # one-off loss at the *start* of a rain event, since canopy/litter can
    # only intercept so much once it's already saturated).
    in_rain_event = False
    event_cumulative_rain = 0.0

    cell_start_date = dates[0]

    for i in range(n):
        date = dates[i]
        temp_c = temps[i]
        rain_mm = rains[i]
        dt = gaps_days[i]

        # ---- KBDI update (metric form) ----
        if rain_mm > 0:
            if not in_rain_event:
                # First day of a new rain event: apply the 5mm interception
                # buffer once.
                net_rain = max(rain_mm - 5.0, 0.0)
                in_rain_event = True
                event_cumulative_rain = rain_mm
            else:
                # Continuing an existing rain event: no repeated
                # interception, the buffer already applied.
                net_rain = rain_mm
                event_cumulative_rain += rain_mm
        else:
            net_rain = 0.0
            if in_rain_event:
                # Event just ended -- bank its total for Drought Factor's
                # "last rain event amount" (P), then reset.
                last_rain_amt = event_cumulative_rain
                in_rain_event = False
                event_cumulative_rain = 0.0

        q_after_rain = max(q_prev - net_rain * 10, 0.0)  # mm -> KBDI units (x10)

        dq = ((203.2 - q_after_rain) *
              (0.968 * np.exp(0.0875 * temp_c + 1.5552) - 8.30) * dt /
              (1 + 10.88 * np.exp(-0.001736 * MEAN_ANNUAL_RAINFALL_MM))) * 1e-3
        dq = max(dq, 0.0)  # KBDI never decreases from dryness alone

        q_new = min(q_after_rain + dq, 203.2)
        kbdi[i] = q_new
        q_prev = q_new

        # ---- Days since rain / last rain amount (for Drought Factor) ----
        # FIX 2: last_rain_amt now holds the *total* rainfall of the most
        # recently completed rain event (banked above when the event ends),
        # not just a single day's rainfall -- matching Griffiths' P, which is
        # defined as the rainfall recorded in the last rain period, not the
        # last individual day it rained.
        if rain_mm >= 2.0:
            n_dry_days = 0.0
        else:
            n_dry_days += dt
        days_since_rain[i] = n_dry_days
        last_rain_amount[i] = last_rain_amt

        # ---- Drought Factor (Griffiths, 1999) ----
        # CONFIRM these coefficients against the original paper before
        # citing in the report -- flagged as an existing known limitation.
        N = max(n_dry_days, 0.0)
        P = max(last_rain_amt, 1.0)  # avoid div-by-zero on first-ever dry run
        df_val = (0.191 * (q_new + 104) * (N + 1) ** 1.5) / \
                  (3.52 * (N + 1) ** 1.5 + P - 1)
        drought_factor[i] = min(max(df_val, 0.0), 10.0)

        days_since_cell_start[i] = (date - cell_start_date) / np.timedelta64(1, "D")

    group = group.copy()
    group["kbdi"] = kbdi
    group["drought_factor"] = drought_factor
    group["days_since_rain"] = days_since_rain
    group["days_since_cell_start"] = days_since_cell_start
    group["kbdi_spinup_flag"] = group["days_since_cell_start"] < KBDI_SPINUP_DAYS
    return group

def compute_ffdi(temp_c, rh, wind_kmh, drought_factor):
    """
    McArthur Mark 5 FFDI, empirical form (Noble et al., 1980).
    wind_kmh: 10m wind speed in km/h -- CONFIRM your weather fetch's units;
    Open-Meteo's default wind speed unit is km/h, but re-verify.
    """
    df_safe = np.maximum(drought_factor, 1e-3)  # ln(0) guard
    ffdi = 2 * np.exp(
        -0.45 + 0.987 * np.log(df_safe)
        - 0.0345 * rh + 0.0338 * temp_c + 0.0234 * wind_kmh
    )
    return ffdi

def compute_ros(ffdi):
    """
    Simplified Rate of Spread (km/h) estimate.
    KNOWN LIMITATION: uses a fixed fuel load constant, not a spatial layer.
    """
    # Fixed fuel load (t/ha) for the simplified Rate of Spread estimate --
    # KNOWN LIMITATION: not a spatial fuel layer.
    FIXED_FUEL_LOAD_T_HA = 8.0

    return 0.0012 * ffdi * FIXED_FUEL_LOAD_T_HA

def engineer_features(df):
    """Runs the full fire-danger feature engineering stage on cleaned data."""
    # decide at analysis time whether to exclude them.
    KBDI_SPINUP_DAYS = 30

    print("Feature engineering -- starting.")

    required = ["temperature_2m", "relative_humidity_2m", "wind_speed_10m",
                "precipitation", "lat_round", "lon_round", "acq_date"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise KeyError(f"Missing required columns for feature engineering: {missing}")

    df = df.copy()
    df["acq_date"] = pd.to_datetime(df["acq_date"])

    # ---- IMPROVEMENT: explicit missing-value handling ----
    # Previously, NaNs in weather columns would silently propagate through
    # every downstream formula and only surface at validate_output() at the
    # very end -- by then it's unclear which stage introduced them. Handling
    # it here, explicitly, means a bad live-fetch batch or a partial weather
    # match fails loudly and immediately instead of quietly corrupting FFDI.
    critical_cols = ["temperature_2m", "relative_humidity_2m", "wind_speed_10m"]
    n_before = len(df)
    n_missing_critical = df[critical_cols].isna().any(axis=1).sum()
    if n_missing_critical:
        print(f"{n_missing_critical:,} rows have missing temperature/"
                    f"humidity/wind -- dropping them (can't compute fire danger "
                    f"indices without these).")
        df = df[~df[critical_cols].isna().any(axis=1)].reset_index(drop=True)

    # Precipitation missing is treated differently: a missing rain reading
    # most plausibly means "no rain recorded" rather than "unknown," so we
    # fill rather than drop -- but log how often this happens, since a high
    # rate would mean that assumption is wrong for this data.
    n_missing_precip = df["precipitation"].isna().sum()
    if n_missing_precip:
        print(f"{n_missing_precip:,} rows ({100*n_missing_precip/len(df):.2f}%) "
                    f"had missing precipitation -- filled with 0.")
        df["precipitation"] = df["precipitation"].fillna(0.0)

    if len(df) < n_before:
        print(f"Rows after missing-value handling: {len(df):,} (was {n_before:,})")

    # ---- IMPROVEMENT: wind-speed unit sanity check ----
    # FFDI's coefficients assume km/h. If the weather source is ever
    # reconfigured (or a live-fetch config drifts) to return m/s instead,
    # every FFDI value silently comes out wrong with no error -- this just
    # warns if the data looks implausible for km/h.
    median_wind = df["wind_speed_10m"].median()
    if median_wind < 3:
        print(f"Median wind_speed_10m is {median_wind:.2f} -- unusually low "
                    f"for km/h. Confirm this isn't actually in m/s before trusting FFDI.")
    elif median_wind > 120:
        print(f"Median wind_speed_10m is {median_wind:.2f} -- unusually high "
                    f"for km/h. Confirm units before trusting FFDI.")

    # ---- EMC (vectorised, no recursion needed) ----
    df["emc"] = compute_emc(
        df["relative_humidity_2m"].to_numpy(dtype=float),
        df["temperature_2m"].to_numpy(dtype=float),
    )
    print("EMC computed.")

    # ---- KBDI + Drought Factor (recursive, per grid cell) ----
    print("Computing KBDI + Drought Factor per grid cell "
             "(this loops through each cell chronologically -- may take a "
             "few minutes on the full dataset)...")
    n_cells = df.groupby(["lat_round", "lon_round"]).ngroups
    print(f"{n_cells:,} grid cells to process.")

    # Manual groupby-and-concat rather than groupby().apply(): newer pandas
    # versions drop the grouping columns (lat_round/lon_round) by default
    # inside .apply(), and the include_groups fix for that isn't consistent
    # across versions. Looping and concatenating keeps every column, since
    # each group DataFrame here is a plain slice of the original.
    processed_groups = [
        compute_kbdi_and_df(group)
        for _, group in df.groupby(["lat_round", "lon_round"], sort=False)
    ]
    df = pd.concat(processed_groups, ignore_index=True)
    print("KBDI + Drought Factor computed.")

    # ---- FFDI ----
    df["ffdi"] = compute_ffdi(
        df["temperature_2m"].to_numpy(dtype=float),
        df["relative_humidity_2m"].to_numpy(dtype=float),
        df["wind_speed_10m"].to_numpy(dtype=float),
        df["drought_factor"].to_numpy(dtype=float),
    )
    print("FFDI computed.")

    # ---- Rate of Spread ----
    df["rate_of_spread"] = compute_ros(df["ffdi"].to_numpy(dtype=float))
    print("Rate of Spread computed.")

    n_spinup = int(df["kbdi_spinup_flag"].sum())
    print(f"{n_spinup:,} rows ({100 * n_spinup / len(df):.1f}%) flagged as "
             f"KBDI spin-up (first {KBDI_SPINUP_DAYS} days per cell).")

    return df

